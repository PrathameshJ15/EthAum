import { Request, Response, NextFunction } from 'express'
import { z } from 'zod'
import { paymentService } from '../services/payment/paymentService.js'
import { sendSuccess } from '../utils/apiResponse.js'
import { ValidationError, UnauthorizedError } from '../utils/apiError.js'
import { PaymentProviderName } from '../types/index.js'

export const createOrderSchema = z
  .object({
    caseId: z.string().min(1, 'Case ID is required'),
    purpose: z.enum([
      'CONSULTATION_FEE',
      'TREATMENT_DEPOSIT',
      'HOSPITAL_ADMISSION',
      'SECOND_OPINION',
    ]),
    bookingId: z.string().optional(),
    appointmentId: z.string().optional(),
    customNotes: z.string().optional(),
    idempotencyKey: z.string().optional(),
    // Anti-tamper: Client-supplied amount is explicitly disallowed to prevent price manipulation
    amount: z.any().optional(),
    currency: z.any().optional(),
  })
  .superRefine((data, ctx) => {
    if (data.amount !== undefined) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Security violation: Payment amounts are strictly server-determined and cannot be supplied by the client.',
        path: ['amount'],
      })
    }
  })

export const verifyPaymentSchema = z.object({
  paymentId: z.string().min(1, 'Payment ID is required'),
  providerOrderId: z.string().min(1, 'Provider order ID is required'),
  providerPaymentId: z.string().min(1, 'Provider payment ID is required'),
  providerSignature: z.string().min(1, 'Provider signature is required'),
})

export const refundPaymentSchema = z.object({
  amount: z.number().positive('Refund amount must be positive').optional(),
  reason: z.string().optional(),
})

export const paymentController = {
  async getConfig(_req: Request, res: Response, next: NextFunction) {
    try {
      const config = paymentService.getPublicConfig()
      return sendSuccess(res, config)
    } catch (err) {
      next(err)
    }
  },

  async createOrder(req: Request, res: Response, next: NextFunction) {
    try {
      if (!req.user) {
        throw new UnauthorizedError('Authentication required to create a payment order')
      }

      const { payment, order } = await paymentService.createPaymentOrder(req.body, {
        id: req.user.id,
        role: req.user.role,
        patientId: req.user.patientId,
        name: req.user.name,
      })

      return sendSuccess(
        res,
        { payment, order },
        'Payment order successfully generated by sovereign server',
        201
      )
    } catch (err) {
      next(err)
    }
  },

  async verifyPayment(req: Request, res: Response, next: NextFunction) {
    try {
      if (!req.user) {
        throw new UnauthorizedError('Authentication required to verify payment')
      }

      const verifiedPayment = await paymentService.verifyPayment(req.body, {
        id: req.user.id,
        role: req.user.role,
        patientId: req.user.patientId,
      })

      return sendSuccess(res, verifiedPayment, 'Payment verified and escrow authorized successfully')
    } catch (err) {
      next(err)
    }
  },

  async handleWebhook(req: Request, res: Response, next: NextFunction) {
    try {
      const providerParam = (req.params.provider || req.query.provider) as PaymentProviderName
      const providerName: PaymentProviderName =
        providerParam ||
        ((req.headers['x-razorpay-signature'] ? 'razorpay' : req.headers['stripe-signature'] ? 'stripe' : 'mock') as PaymentProviderName)

      // Signature header extraction
      const signatureHeader =
        (req.headers['x-razorpay-signature'] as string) ||
        (req.headers['stripe-signature'] as string) ||
        (req.headers['x-mock-signature'] as string) ||
        (req.query.signature as string) ||
        ''

      if (!signatureHeader) {
        throw new ValidationError('Missing payment provider cryptographic signature header')
      }

      // Raw body buffer
      const rawBody = (req as any).rawBody || Buffer.from(JSON.stringify(req.body), 'utf-8')

      const result = await paymentService.handleWebhook(
        providerName,
        rawBody,
        signatureHeader,
        req.headers
      )

      return sendSuccess(res, result, 'Webhook event processed idempotently')
    } catch (err) {
      next(err)
    }
  },

  async listPayments(req: Request, res: Response, next: NextFunction) {
    try {
      if (!req.user) {
        throw new UnauthorizedError('Authentication required to view payment history')
      }

      const caseId = req.query.caseId as string
      const payments = await paymentService.listPayments(
        {
          id: req.user.id,
          role: req.user.role,
          patientId: req.user.patientId,
        },
        { caseId }
      )

      return sendSuccess(res, payments)
    } catch (err) {
      next(err)
    }
  },

  async getPaymentById(req: Request, res: Response, next: NextFunction) {
    try {
      if (!req.user) {
        throw new UnauthorizedError('Authentication required to inspect payment record')
      }

      const payment = await paymentService.getPaymentById(req.params.id as string, {
        id: req.user.id,
        role: req.user.role,
        patientId: req.user.patientId,
      })

      return sendSuccess(res, payment)
    } catch (err) {
      next(err)
    }
  },

  async refundPayment(req: Request, res: Response, next: NextFunction) {
    try {
      if (!req.user) {
        throw new UnauthorizedError('Authentication required to process refunds')
      }

      const { amount, reason } = req.body
      const payment = await paymentService.refundPayment(
        req.params.id as string,
        amount,
        reason,
        { id: req.user.id, role: req.user.role }
      )

      return sendSuccess(res, payment, 'Payment refund processed successfully')
    } catch (err) {
      next(err)
    }
  },
}
